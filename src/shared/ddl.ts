import type {
  ColumnSnapshot,
  DbEngine,
  DdlColumnDef,
  DdlOperation,
  TableAlteration
} from './types'

// MariaDB shares MySQL's SQL dialect: backtick identifiers, `db`.`table`
// qualification and the same DDL/privilege grammar.
export function isMysqlFamily(engine: DbEngine): boolean {
  return engine === 'mysql' || engine === 'mariadb'
}

export function quoteIdent(engine: DbEngine, ident: string): string {
  if (isMysqlFamily(engine)) return '`' + ident.replace(/`/g, '``') + '`'
  return '"' + ident.replace(/"/g, '""') + '"'
}

export function qualifiedTable(
  engine: DbEngine,
  table: string,
  schema?: string,
  database?: string
): string {
  if (engine === 'postgres') {
    return schema
      ? `${quoteIdent(engine, schema)}.${quoteIdent(engine, table)}`
      : quoteIdent(engine, table)
  }
  if (engine === 'oracle') {
    // Oracle "schema" is the owning user; no separate database qualifier.
    return schema
      ? `${quoteIdent(engine, schema)}.${quoteIdent(engine, table)}`
      : quoteIdent(engine, table)
  }
  if (isMysqlFamily(engine)) {
    const qualifier = database ?? schema
    return qualifier
      ? `${quoteIdent(engine, qualifier)}.${quoteIdent(engine, table)}`
      : quoteIdent(engine, table)
  }
  return quoteIdent(engine, table)
}

function columnDefinition(
  engine: DbEngine,
  col: DdlColumnDef,
  includePrimaryKey = true
): string {
  const auto = col.autoIncrement === true

  // SQLite only accepts AUTOINCREMENT on an INTEGER PRIMARY KEY, so the type
  // and key clause are forced no matter what the form submitted.
  if (engine === 'sqlite' && auto) {
    return `${quoteIdent(engine, col.name)} INTEGER PRIMARY KEY AUTOINCREMENT`
  }

  let def = `${quoteIdent(engine, col.name)} ${col.dataType}`
  if (auto) {
    if (engine === 'postgres') {
      // serial/bigserial already own a sequence; other types need IDENTITY.
      if (!/^(small|big)?serial$/i.test(col.dataType.trim())) {
        def += ' GENERATED BY DEFAULT AS IDENTITY'
      }
    } else if (isMysqlFamily(engine)) {
      def += ' AUTO_INCREMENT'
    } else if (engine === 'oracle') {
      def += ' GENERATED BY DEFAULT AS IDENTITY'
    }
  }
  if (includePrimaryKey && col.primaryKey) def += ' PRIMARY KEY'
  const isKey = includePrimaryKey && col.primaryKey
  if (!col.nullable && !isKey) def += ' NOT NULL'
  // Identity/serial columns generate their own value; a literal DEFAULT would
  // conflict with the sequence.
  if (!auto && col.defaultValue !== undefined && col.defaultValue !== '') {
    def += ` DEFAULT ${col.defaultValue}`
  }
  return def
}

function sqlString(value: string): string {
  return "'" + value.replace(/'/g, "''") + "'"
}

// Turns a stored default (as reported by information_schema) into a clause we
// can safely drop or re-apply. Identity/serial defaults are owned by the
// sequence and must be left alone.
function isSequenceDefault(value: string | null | undefined): boolean {
  if (!value) return false
  return /nextval\(|IDENTITY|GENERATED/i.test(value)
}

function alterTableStatements(
  engine: DbEngine,
  table: string,
  alterations: TableAlteration[]
): string[] {
  const statements: string[] = []
  const q = (name: string): string => quoteIdent(engine, name)

  // Primary-key changes are emitted after column edits so the referenced
  // columns already exist (or no longer exist) when the constraint is applied.
  const pkChanges = alterations.filter(
    (a) => a.type === 'setPrimaryKey' || a.type === 'dropPrimaryKey'
  )
  const mysqlFamily = isMysqlFamily(engine)

  // MySQL requires the auto-increment column to already be a key, so a column
  // gaining AUTO_INCREMENT must be modified AFTER the PK is (re)created, while
  // one losing it must be modified BEFORE the PK is dropped.
  const afterPk: string[] = []

  for (const alt of alterations) {
    if (alt.type === 'setPrimaryKey' || alt.type === 'dropPrimaryKey') continue

    if (alt.type === 'addColumn') {
      statements.push(`ALTER TABLE ${table} ADD COLUMN ${columnDefinition(engine, alt.column)};`)
      continue
    }
    if (alt.type === 'dropColumn') {
      statements.push(`ALTER TABLE ${table} DROP COLUMN ${q(alt.name)};`)
      continue
    }
    if (alt.type === 'renameColumn') {
      statements.push(`ALTER TABLE ${table} RENAME COLUMN ${q(alt.from)} TO ${q(alt.to)};`)
      continue
    }
    if (alt.type === 'setColumnComment') {
      statements.push(
        ...columnCommentStatements(engine, table, alt.column, alt.comment, alt.definition)
      )
      continue
    }
    if (alt.type === 'setTableComment') {
      statements.push(...tableCommentStatements(engine, table, alt.comment))
      continue
    }
    if (alt.type === 'modifyColumn') {
      const gainedAuto =
        mysqlFamily && (alt.column.autoIncrement === true) && !alt.previous?.autoIncrement
      const stmts = modifyColumnStatements(engine, table, alt.column, alt.previous)
      if (gainedAuto) afterPk.push(...stmts)
      else statements.push(...stmts)
    }
  }

  for (const alt of pkChanges) {
    if (alt.type === 'dropPrimaryKey') {
      statements.push(...dropPrimaryKeyStatements(engine, table, alt.constraintName))
    } else {
      statements.push(...setPrimaryKeyStatements(engine, table, alt.columns))
    }
  }

  statements.push(...afterPk)
  return statements
}

// Comments: Postgres/Oracle use a dedicated COMMENT ON statement, MySQL needs
// the comment inlined in ALTER TABLE ... MODIFY/COMMENT.
function columnCommentStatements(
  engine: DbEngine,
  table: string,
  column: string,
  comment: string | null,
  definition?: DdlColumnDef
): string[] {
  const q = (name: string): string => quoteIdent(engine, name)
  if (isMysqlFamily(engine)) {
    if (!definition) {
      throw new Error(
        'Komentar kolom MySQL butuh definisi kolom lengkap (MODIFY COLUMN).'
      )
    }
    // An empty comment must not be emitted as "COMMENT ;", which is a syntax
    // error. MySQL clears a comment with an empty string literal instead.
    const clause = comment === null ? " COMMENT ''" : ` COMMENT ${sqlString(comment)}`
    return [
      `ALTER TABLE ${table} MODIFY COLUMN ${columnDefinition(engine, definition, false)}${clause};`
    ]
  }
  if (engine === 'sqlite') {
    throw new Error('SQLite tidak mendukung komentar kolom.')
  }
  return [
    `COMMENT ON COLUMN ${table}.${q(column)} IS ${comment === null ? 'NULL' : sqlString(comment)};`
  ]
}

function tableCommentStatements(
  engine: DbEngine,
  table: string,
  comment: string | null
): string[] {
  if (isMysqlFamily(engine)) {
    const text = comment === null ? '' : sqlString(comment)
    return [`ALTER TABLE ${table} COMMENT = ${text};`]
  }
  if (engine === 'sqlite') {
    throw new Error('SQLite tidak mendukung komentar tabel.')
  }
  return [`COMMENT ON TABLE ${table} IS ${comment === null ? 'NULL' : sqlString(comment)};`]
}

// Postgres serial pseudo-types are CREATE TABLE shorthands, not real column
// types, so ALTER COLUMN cannot target them. Map to the base type instead.
const PG_SERIAL_BASE: Record<string, string> = {
  smallserial: 'smallint',
  serial2: 'smallint',
  serial: 'integer',
  serial4: 'integer',
  bigserial: 'bigint',
  serial8: 'bigint'
}

function modifyColumnStatements(
  engine: DbEngine,
  table: string,
  col: DdlColumnDef,
  previous?: ColumnSnapshot
): string[] {
  const q = (name: string): string => quoteIdent(engine, name)

  // `MODIFY COLUMN` re-declares the column but never its key, so the inline
  // PRIMARY KEY clause is left out here: the PK is added or dropped by the
  // dedicated primary-key statements.
  if (isMysqlFamily(engine)) {
    return [
      `ALTER TABLE ${table} MODIFY COLUMN ${columnDefinition(engine, col, false)};`
    ]
  }
  if (engine === 'oracle') {
    const def = columnDefinition(engine, col, false)
    // Oracle keeps NOT NULL implicit for keys; re-declare the nullability when
    // the column is not part of the new key so the intent survives.
    return [`ALTER TABLE ${table} MODIFY (${def});`]
  }
  if (engine === 'sqlite') {
    // SQLite cannot ALTER a column in place; the caller must rebuild the table.
    // We surface a clear error instead of emitting invalid SQL.
    throw new Error(
      'SQLite tidak mendukung ubah tipe/constraint kolom. Buat tabel baru lalu salin data.'
    )
  }

  // Postgres: apply only the differences, in dependency-safe order.
  const prev = previous
  const requested = col.dataType.trim().toLowerCase()
  const serialBase = PG_SERIAL_BASE[requested]
  // A serial type always implies a generated value; keep the user's AI flag too.
  const effectiveType = serialBase ?? col.dataType.trim()
  const wantsAuto = col.autoIncrement === true || serialBase !== undefined
  const prevAuto = prev?.autoIncrement ?? false

  const typeChanged = !prev || normalizeType(prev.dataType) !== normalizeType(effectiveType)
  const autoChanged = prevAuto !== wantsAuto

  const stmts: string[] = []

  if (typeChanged) {
    stmts.push(
      `ALTER TABLE ${table} ALTER COLUMN ${q(col.name)} TYPE ${effectiveType} USING ${q(
        col.name
      )}::${effectiveType};`
    )
  }

  if (autoChanged) {
    // A pre-existing nextval default (old-style serial) blocks ADD IDENTITY, so
    // clear it first in both directions.
    if (isSequenceDefault(prev?.defaultValue)) {
      stmts.push(`ALTER TABLE ${table} ALTER COLUMN ${q(col.name)} DROP DEFAULT;`)
    }
    if (wantsAuto) {
      stmts.push(
        `ALTER TABLE ${table} ALTER COLUMN ${q(col.name)} ADD GENERATED BY DEFAULT AS IDENTITY;`
      )
      // Point the new sequence past any existing rows so the next insert does
      // not reuse a value already in the column.
      const tableText = table.replace(/'/g, "''")
      const colText = col.name.replace(/'/g, "''")
      stmts.push(
        `SELECT setval(pg_get_serial_sequence('${tableText}', '${colText}'), ` +
          `COALESCE((SELECT MAX(${q(col.name)}) FROM ${table}), 1), ` +
          `(SELECT COUNT(*) > 0 FROM ${table}));`
      )
    } else {
      stmts.push(`ALTER TABLE ${table} ALTER COLUMN ${q(col.name)} DROP IDENTITY IF EXISTS;`)
    }
  }

  const prevNullable = prev?.nullable ?? true
  if (prevNullable !== col.nullable && !col.primaryKey) {
    stmts.push(
      `ALTER TABLE ${table} ALTER COLUMN ${q(col.name)} ${
        col.nullable ? 'DROP' : 'SET'
      } NOT NULL;`
    )
  }

  const prevDefault = prev?.defaultValue ?? null
  const nextDefault = col.defaultValue && col.defaultValue !== '' ? col.defaultValue : null
  if ((prevDefault ?? null) !== nextDefault && !isSequenceDefault(prevDefault)) {
    if (nextDefault === null) {
      stmts.push(`ALTER TABLE ${table} ALTER COLUMN ${q(col.name)} DROP DEFAULT;`)
    } else {
      stmts.push(
        `ALTER TABLE ${table} ALTER COLUMN ${q(col.name)} SET DEFAULT ${nextDefault};`
      )
    }
  }
  return stmts
}

function normalizeType(type: string): string {
  return type.trim().toLowerCase().replace(/\s+/g, ' ')
}

function setPrimaryKeyStatements(
  engine: DbEngine,
  table: string,
  columns: string[]
): string[] {
  const cols = columns.map((c) => quoteIdent(engine, c)).join(', ')
  return [`ALTER TABLE ${table} ADD PRIMARY KEY (${cols});`]
}

function dropPrimaryKeyStatements(
  engine: DbEngine,
  table: string,
  constraintName?: string | null
): string[] {
  if (isMysqlFamily(engine)) {
    return [`ALTER TABLE ${table} DROP PRIMARY KEY;`]
  }
  const name = constraintName ? quoteIdent(engine, constraintName) : `${table}_pkey`
  if (engine === 'oracle') {
    return [`ALTER TABLE ${table} DROP PRIMARY KEY;`]
  }
  return [`ALTER TABLE ${table} DROP CONSTRAINT ${name};`]
}

// SQLite has no TRUNCATE; resetting auto-increment means clearing
// sqlite_sequence, which only exists once an AUTOINCREMENT table is created.
export function sqliteTruncateStatements(table: string): string[] {
  return [
    `DELETE FROM ${quoteIdent('sqlite', table)};`,
    `DELETE FROM sqlite_sequence WHERE name = ${sqlString(table)};`
  ]
}

export function buildDdl(engine: DbEngine, op: DdlOperation): string[] {
  switch (op.kind) {
    case 'createTable': {
      const table = qualifiedTable(engine, op.table, op.schema, op.database)
      // SQLite keeps AUTOINCREMENT on an inline INTEGER PRIMARY KEY; every
      // other engine takes a single table-level PRIMARY KEY constraint so
      // composite keys are valid.
      const sqliteInlineAuto =
        engine === 'sqlite' && op.columns.some((c) => c.autoIncrement)
      const pkColumns = op.columns.filter((c) => c.primaryKey).map((c) => c.name)
      const defs = op.columns.map((c) => '  ' + columnDefinition(engine, c, false))
      if (!sqliteInlineAuto && pkColumns.length > 0) {
        const cols = pkColumns.map((c) => quoteIdent(engine, c)).join(', ')
        defs.push(`  PRIMARY KEY (${cols})`)
      }
      return [`CREATE TABLE ${table} (\n${defs.join(',\n')}\n);`]
    }
    case 'dropTable': {
      const table = qualifiedTable(engine, op.table, op.schema, op.database)
      return [`DROP TABLE ${table};`]
    }
    case 'addColumn': {
      const table = qualifiedTable(engine, op.table, op.schema, op.database)
      return [`ALTER TABLE ${table} ADD COLUMN ${columnDefinition(engine, op.column)};`]
    }
    case 'dropColumn': {
      const table = qualifiedTable(engine, op.table, op.schema, op.database)
      return [`ALTER TABLE ${table} DROP COLUMN ${quoteIdent(engine, op.column)};`]
    }
    case 'createIndex': {
      const table = qualifiedTable(engine, op.table, op.schema, op.database)
      const unique = op.unique ? 'UNIQUE ' : ''
      const cols = op.columns.map((c) => quoteIdent(engine, c)).join(', ')
      return [
        `CREATE ${unique}INDEX ${quoteIdent(engine, op.indexName)} ON ${table} (${cols});`
      ]
    }
    case 'dropIndex': {
      if (isMysqlFamily(engine)) {
        const table = qualifiedTable(engine, op.table, op.schema, op.database)
        return [`DROP INDEX ${quoteIdent(engine, op.indexName)} ON ${table};`]
      }
      if (engine === 'postgres' && op.schema) {
        return [
          `DROP INDEX ${quoteIdent(engine, op.schema)}.${quoteIdent(engine, op.indexName)};`
        ]
      }
      if (engine === 'oracle' && op.schema) {
        return [
          `DROP INDEX ${quoteIdent(engine, op.schema)}.${quoteIdent(engine, op.indexName)};`
        ]
      }
      return [`DROP INDEX ${quoteIdent(engine, op.indexName)};`]
    }
    case 'createDatabase': {
      return [`CREATE DATABASE ${quoteIdent(engine, op.database)};`]
    }
    case 'dropDatabase': {
      return [`DROP DATABASE ${quoteIdent(engine, op.database)};`]
    }
    case 'createSchema': {
      return [`CREATE SCHEMA ${quoteIdent(engine, op.schema)};`]
    }
    case 'dropSchema': {
      return [`DROP SCHEMA ${quoteIdent(engine, op.schema)};`]
    }
    case 'truncateTable': {
      const table = qualifiedTable(engine, op.table, op.schema, op.database)
      // SQLite is handled by the adapter (DELETE + optional sequence reset)
      // because sqlite_sequence only exists when AUTOINCREMENT was used.
      if (engine === 'sqlite') return [`DELETE FROM ${table};`]
      return [`TRUNCATE TABLE ${table};`]
    }
    case 'emptyTable': {
      const table = qualifiedTable(engine, op.table, op.schema, op.database)
      return [`DELETE FROM ${table};`]
    }
    case 'renameTable': {
      const table = qualifiedTable(engine, op.table, op.schema, op.database)
      if (isMysqlFamily(engine)) {
        return [`RENAME TABLE ${table} TO ${quoteIdent(engine, op.newName)};`]
      }
      if (engine === 'postgres') {
        // RENAME TO takes a bare name; a schema-qualified target is a syntax
        // error ("syntax error at or near ."). Moving a table between schemas
        // is SET SCHEMA, which this operation does not claim to do.
        return [`ALTER TABLE ${table} RENAME TO ${quoteIdent(engine, op.newName)};`]
      }
      return [`ALTER TABLE ${table} RENAME TO ${quoteIdent(engine, op.newName)};`]
    }
    case 'alterTable': {
      const table = qualifiedTable(engine, op.table, op.schema, op.database)
      return alterTableStatements(engine, table, op.alterations)
    }
    case 'createForeignKey': {
      const table = qualifiedTable(engine, op.table, op.schema, op.database)
      const cols = op.columns.map((c) => quoteIdent(engine, c)).join(', ')
      const refTable = qualifiedTable(
        engine,
        op.refTable,
        op.refSchema ?? op.schema,
        op.database
      )
      const refCols = op.refColumns.map((c) => quoteIdent(engine, c)).join(', ')
      const name = op.name ? `CONSTRAINT ${quoteIdent(engine, op.name)} ` : ''
      const actions: string[] = []
      if (op.onUpdate) actions.push(` ON UPDATE ${op.onUpdate}`)
      if (op.onDelete) actions.push(` ON DELETE ${op.onDelete}`)
      return [
        `ALTER TABLE ${table} ADD ${name}FOREIGN KEY (${cols}) REFERENCES ${refTable} (${refCols})${actions.join('')};`
      ]
    }
    case 'dropForeignKey': {
      const table = qualifiedTable(engine, op.table, op.schema, op.database)
      if (isMysqlFamily(engine)) {
        return [`ALTER TABLE ${table} DROP FOREIGN KEY ${quoteIdent(engine, op.name)};`]
      }
      return [`ALTER TABLE ${table} DROP CONSTRAINT ${quoteIdent(engine, op.name)};`]
    }
    case 'createView': {
      const view = qualifiedTable(engine, op.view, op.schema, op.database)
      const clause = op.orReplace ? 'OR REPLACE ' : ''
      const body = op.selectSql.trim().replace(/;\s*$/, '')
      return [`CREATE ${clause}VIEW ${view} AS\n${body};`]
    }
    case 'dropView': {
      const view = qualifiedTable(engine, op.view, op.schema, op.database)
      return [`DROP VIEW ${view};`]
    }
    case 'dropRoutine': {
      const name = qualifiedTable(engine, op.routine, op.schema, op.database)
      if (op.routineKind === 'trigger') {
        if (engine === 'postgres') {
          // Postgres triggers live on a table, so the DROP must name it.
          const tbl = qualifiedTable(engine, op.onTable ?? '', op.schema, op.database)
          return [`DROP TRIGGER ${quoteIdent(engine, op.routine)} ON ${tbl};`]
        }
        return [`DROP TRIGGER ${name};`]
      }
      if (op.routineKind === 'event') {
        return [`DROP EVENT ${name};`]
      }
      const kw = op.routineKind === 'procedure' ? 'PROCEDURE' : 'FUNCTION'
      // Postgres needs the argument list to disambiguate overloaded functions.
      const sig =
        engine === 'postgres' && op.routineKind === 'function'
          ? op.signature ?? ''
          : ''
      return [`DROP ${kw} ${name}${sig};`]
    }
  }
}

export function engineColumnTypes(engine: DbEngine): string[] {
  if (engine === 'postgres') {
    return [
      'integer',
      'bigint',
      'serial',
      'bigserial',
      'text',
      'varchar(255)',
      'boolean',
      'numeric(10,2)',
      'date',
      'timestamp',
      'timestamptz',
      'jsonb',
      'uuid'
    ]
  }
  if (engine === 'oracle') {
    return [
      'NUMBER',
      'NUMBER(10)',
      'NUMBER(10,2)',
      'INTEGER',
      'VARCHAR2(255)',
      'VARCHAR2(4000)',
      'NVARCHAR2(255)',
      'CLOB',
      'DATE',
      'TIMESTAMP',
      'TIMESTAMP WITH TIME ZONE',
      'CHAR(1)',
      'RAW(16)'
    ]
  }
  if (engine === 'sqlite') {
    return ['INTEGER', 'TEXT', 'REAL', 'BLOB', 'NUMERIC']
  }
  return [
    'INT',
    'BIGINT',
    'VARCHAR(255)',
    'TEXT',
    'BOOLEAN',
    'DECIMAL(10,2)',
    'DATE',
    'DATETIME',
    'TIMESTAMP',
    'JSON',
    'BLOB'
  ]
}
