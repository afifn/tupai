export type ColumnInputKind =
  'boolean' | 'date' | 'datetime' | 'time' | 'number' | 'json' | 'text'

export function classifyColumnType(dataType: string): ColumnInputKind {
  const t = dataType.toLowerCase()
  if (t.includes('bool')) return 'boolean'
  if (t.includes('timestamp') || t.includes('datetime')) return 'datetime'
  if (t.includes('date')) return 'date'
  if (t.includes('time')) return 'time'
  if (t.includes('json')) return 'json'
  if (
    t.includes('int') ||
    t.includes('serial') ||
    t.includes('numeric') ||
    t.includes('decimal') ||
    t.includes('number') ||
    t.includes('real') ||
    t.includes('double') ||
    t.includes('float') ||
    t.includes('money')
  ) {
    return 'number'
  }
  return 'text'
}

// datetime-local gives "YYYY-MM-DDTHH:mm"; SQL engines expect a space separator.
export function normalizeDateTime(value: string): string {
  if (!value) return value
  const withSpace = value.replace('T', ' ')
  if (/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}$/.test(withSpace)) return `${withSpace}:00`
  return withSpace
}

// Renders an existing DB value into the string a typed HTML input expects.
export function toInputValue(kind: ColumnInputKind, value: unknown): string {
  if (value === null || value === undefined) return ''
  if (kind === 'boolean')
    return value === true || value === 1 || value === '1' ? 'true' : 'false'
  // A driver may hand back a Date for a date column. JSON.stringify would turn it
  // into a quoted ISO string, which no date input accepts.
  const str =
    value instanceof Date
      ? formatLocalDateTime(value)
      : typeof value === 'object'
        ? JSON.stringify(value)
        : String(value)
  if (kind === 'datetime') return str.replace(' ', 'T').slice(0, 16)
  if (kind === 'date') return str.slice(0, 10)
  if (kind === 'time') return str.slice(0, 8)
  return str
}

// Local wall-clock text, matching what the database reported instead of shifting
// the value into UTC the way toISOString() does.
function formatLocalDateTime(value: Date): string {
  const pad = (n: number): string => String(n).padStart(2, '0')
  return (
    `${value.getFullYear()}-${pad(value.getMonth() + 1)}-${pad(value.getDate())} ` +
    `${pad(value.getHours())}:${pad(value.getMinutes())}:${pad(value.getSeconds())}`
  )
}

// Converts a typed input string into the value to send to the database.
export function coerceInput(kind: ColumnInputKind, raw: string): unknown {
  if (kind === 'boolean') return raw === 'true'
  if (kind === 'number') {
    const num = Number(raw)
    if (Number.isNaN(num)) throw new Error('Nilai harus berupa angka.')
    return num
  }
  if (kind === 'datetime') return normalizeDateTime(raw)
  return raw
}

export function inputElementType(
  kind: ColumnInputKind
): 'text' | 'number' | 'date' | 'time' | 'datetime-local' {
  if (kind === 'number') return 'number'
  if (kind === 'date') return 'date'
  if (kind === 'time') return 'time'
  if (kind === 'datetime') return 'datetime-local'
  return 'text'
}

export function isAutoGeneratedColumn(
  dataType: string,
  defaultValue: string | null,
  autoIncrement?: boolean
): boolean {
  // The driver knows best: SQLite rowid aliases and Postgres IDENTITY columns do
  // not carry a type name or default that can be recognised from here.
  if (autoIncrement === true) return true
  const t = dataType.toLowerCase()
  return (
    t.includes('serial') ||
    t.includes('autoincrement') ||
    (defaultValue !== null && /nextval|autoincrement/i.test(defaultValue))
  )
}
