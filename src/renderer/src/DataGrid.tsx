export function DataGrid({
  selection,
  onInspectRow,
  inspectedRowKey,
  filterOpen
}: Props): JSX.Element {
  const { tr, errorText } = useLocale()
  const [page, setPage] = useState(0)
  const { settings } = useSettings()
  // The default page size comes from Settings; the pager can still override it
  // for the current tab.
  const [pageSize, setPageSize] = useState(settings.grid.pageSize)
  // Text being typed in the page box. Kept separate from `page` so a partially
  // typed number never triggers a load, and cleared when the page changes by any
  // other route (chevrons, page size, reload).
  const [pageDraft, setPageDraft] = useState('')
  const [data, setData] = useState<PageResult | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [orderBy, setOrderBy] = useState<string | undefined>(undefined)
  const [orderDir, setOrderDir] = useState<'asc' | 'desc'>('asc')
  const [advancedFilters, setAdvancedFilters] = useState<ColumnFilter[]>([])
  const debouncedAdvancedFilters = useDebouncedValue(advancedFilters, 250)
  const [filterLogic, setFilterLogic] = useState<'and' | 'or'>('and')
  const [filtersOpen, setFiltersOpen] = useState(filterOpen ?? false)
  const [edit, setEdit] = useState<EditState | null>(null)
  const [busy, setBusy] = useState(false)
  const [draft, setDraft] = useState<Record<string, string> | null>(null)
  const [colWidths, setColWidths] = useState<Record<string, number>>({})
  const [selected, setSelected] = useState<Set<string>>(new Set())
  const [menu, setMenu] = useState<CellContext | null>(null)
  const [preview, setPreview] = useState<BinaryCell | null>(null)
  // The row that was just written. A short tint confirms the save in place, so
  // the user keeps their bearings instead of hunting for the row after a reload.
  const [savedKey, setSavedKey] = useState<string | null>(null)
  const savedTimer = useRef<ReturnType<typeof setTimeout> | null>(null)

  const markSaved = useCallback((key: string): void => {
    // A table without a primary key has no per-row identity to mark.
    if (!key) return
    setSavedKey(key)
    if (savedTimer.current) clearTimeout(savedTimer.current)
    savedTimer.current = setTimeout(() => setSavedKey(null), 1800)
  }, [])

  useEffect(
    () => () => {
      if (savedTimer.current) clearTimeout(savedTimer.current)
    },
    []
  )

  const resizeRef = useRef<{ column: string; startX: number; startWidth: number } | null>(
    null
  )

  // Only the conditions are real filters now. A row with no column, or one whose
  // operator needs a value it does not have, is ignored so a half-typed
  // condition does not empty the grid.
  const activeFilters = useMemo<ColumnFilter[]>(
    () =>
      debouncedAdvancedFilters.filter(
        (f) => f.column && (operatorNeedsValue(f.op) ? (f.value ?? '') !== '' : true)
      ),
    [debouncedAdvancedFilters]
  )

  const fetchPage = useCallback(
    () =>
      unwrap(
        window.dbApi.selectRows({
          connectionId: selection.connectionId,
          database: selection.database,
          schema: selection.schema,
          table: selection.table,
          limit: pageSize,
          offset: page * pageSize,
          orderBy,
          orderDir,
          filters: activeFilters.length > 0 ? activeFilters : undefined,
          filterLogic: activeFilters.length > 0 ? filterLogic : undefined
        })
      ),
    [selection, page, pageSize, orderBy, orderDir, activeFilters, filterLogic]
  )

  // A quiet load refetches the page without unmounting the table: no "Memuat
  // data..." flash, no lost scroll position, and the checkbox selection stays.
  // Mutations use it so a save feels like an in-place update instead of a
  // refresh. A normal load is only for a real navigation (page, filter, sort).
  const load = useCallback(
    async (options?: { quiet?: boolean }): Promise<PageResult | null> => {
      const quiet = options?.quiet === true
      if (!quiet) setLoading(true)
      setError(null)
      try {
        const result = await fetchPage()
        setData(result)
        if (!quiet) setSelected(new Set())
        return result
      } catch (err) {
        setError(errorText(err))
        return null
      } finally {
        if (!quiet) setLoading(false)
      }
    },
    [fetchPage]
  )

  useEffect(() => {
    setPage(0)
    setOrderBy(undefined)
    setEdit(null)
    setColWidths({})
    setAdvancedFilters([])
    setFiltersOpen(false)
    setSavedKey(null)
  }, [selection])

  // The toggle lives in the tab strip now, so the panel follows the shell's
  // flag instead of keeping a second copy of it. Opening an empty panel seeds
  // one blank condition, so the user starts from a row they can fill in rather
  // than from a button they have to find first.
  useEffect(() => {
    if (filterOpen === undefined) return
    setFiltersOpen(filterOpen)
    if (filterOpen) {
      setAdvancedFilters((prev) =>
        prev.length === 0 ? [{ column: '', op: 'contains', value: '' }] : prev
      )
    }
  }, [filterOpen])

  useEffect(() => {
    void load()
  }, [load])

  // A chevron, page-size change, or reload moves `page`; the typed value must
  // not linger and show a page the user is no longer on.
  useEffect(() => {
    setPageDraft('')
  }, [page])

  const columns: ColumnInfo[] = data?.columns ?? []
  const pks: string[] = data?.primaryKeys ?? []
  const canEdit = (data?.hasPrimaryKey ?? false) && pks.length > 0
  // Insert does not need a primary key, so a table with columns can always
  // accept a new row even before it has one.
  const canInsert = columns.length > 0
  const totalPages = data ? Math.max(1, Math.ceil(data.total / pageSize)) : 1
  const rowKeys = (data?.rows ?? []).map((r) => rowKey(r, pks))
  const allSelected = rowKeys.length > 0 && rowKeys.every((k) => selected.has(k))

  const widthOf = (name: string): number => colWidths[name] ?? DEFAULT_COL_WIDTH
  const totalWidth =
    CHECKBOX_COL_WIDTH +
    ACTIONS_COL_WIDTH +
    columns.reduce((sum, c) => sum + widthOf(c.name), 0)

  function toggleSort(col: string): void {
    if (orderBy === col) {
      setOrderDir((d) => (d === 'asc' ? 'desc' : 'asc'))
    } else {
      setOrderBy(col)
      setOrderDir('asc')
    }
  }

  function toggleRow(key: string): void {
    setSelected((prev) => {
      const next = new Set(prev)
      if (next.has(key)) next.delete(key)
      else next.add(key)
      return next
    })
  }

  function toggleAll(): void {
    setSelected(allSelected ? new Set() : new Set(rowKeys))
  }

  // Applies a saved change to the row already on screen. The row keeps its
  // position, so an edit never makes the grid jump or reorder under the cursor.
  function patchRow(rowIndex: number, changes: Record<string, unknown>): void {
    setData((prev) => {
      if (!prev || !prev.rows[rowIndex]) return prev
      const rows = prev.rows.slice()
      rows[rowIndex] = { ...rows[rowIndex], ...changes }
      return { ...prev, rows }
    })
  }

  // Sorting or filtering by the edited column can move the row off this page,
  // and changing a primary key changes the row identity. Only then does the page
  // need to be fetched again, and it is fetched quietly.
  function editNeedsRefetch(column: string): boolean {
    return (
      pks.includes(column) ||
      orderBy === column ||
      activeFilters.some((f) => f.column === column)
    )
  }

  // Keyboard equivalent of dragging the column edge. 16px per press matches the
  // step a small drag usually produces, and Home resets to the default width.
  function resizeByKeyboard(e: React.KeyboardEvent, column: string): void {
    const step = e.shiftKey ? 40 : 16
    if (e.key === 'ArrowLeft' || e.key === 'ArrowRight') {
      e.preventDefault()
      const current = widthOf(column)
      const next = Math.max(
        MIN_COL_WIDTH,
        current + (e.key === 'ArrowRight' ? step : -step)
      )
      setColWidths((prev) => ({ ...prev, [column]: next }))
      return
    }
    if (e.key === 'Home') {
      e.preventDefault()
      setColWidths((prev) => {
        const next = { ...prev }
        delete next[column]
        return next
      })
    }
  }

  function startResize(e: React.MouseEvent, column: string): void {
    e.preventDefault()
    e.stopPropagation()
    resizeRef.current = { column, startX: e.clientX, startWidth: widthOf(column) }
    document.body.classList.add('is-col-resizing')

    function onMove(ev: MouseEvent): void {
      const ref = resizeRef.current
      if (!ref) return
      const next = Math.max(MIN_COL_WIDTH, ref.startWidth + (ev.clientX - ref.startX))
      setColWidths((prev) => ({ ...prev, [ref.column]: next }))
    }
    function onUp(): void {
      resizeRef.current = null
      document.body.classList.remove('is-col-resizing')
      window.removeEventListener('mousemove', onMove)
      window.removeEventListener('mouseup', onUp)
    }
    window.addEventListener('mousemove', onMove)
    window.addEventListener('mouseup', onUp)
  }

  async function commitEdit(): Promise<void> {
    if (!edit || !data) return
    const row = data.rows[edit.rowIndex]
    const column = columns.find((c) => c.name === edit.column)
    if (!column) return
    const pk: Record<string, unknown> = {}
    for (const k of pks) pk[k] = row[k]
    let value: unknown
    try {
      value = coerceInput(classifyColumnType(column.dataType), edit.value)
    } catch (err) {
      setError(tr('grid.columnError', { name: column.name, message: errorText(err) }))
      return
    }
    setBusy(true)
    setError(null)
    try {
      await unwrap(
        window.dbApi.updateRow({
          connectionId: selection.connectionId,
          database: selection.database,
          schema: selection.schema,
          table: selection.table,
          primaryKeys: pk,
          changes: { [edit.column]: value }
        })
      )
      const key = rowKey({ ...row, [edit.column]: value }, pks)
      setEdit(null)
      patchRow(edit.rowIndex, { [edit.column]: value })
      markSaved(key)
      if (editNeedsRefetch(edit.column)) await load({ quiet: true })
    } catch (err) {
      setError(errorText(err))
    } finally {
      setBusy(false)
    }
  }

  function startDraft(): void {
    const next: Record<string, string> = {}
    for (const c of columns) {
      if (isAutoGeneratedColumn(c.dataType, c.defaultValue, c.autoIncrement)) continue
      next[c.name] = classifyColumnType(c.dataType) === 'boolean' ? 'false' : ''
    }
    setDraft(next)
    setError(null)
  }

  async function commitDraft(): Promise<void> {
    if (!draft) return
    const values: Record<string, unknown> = {}
    for (const c of columns) {
      if (!(c.name in draft)) continue
      const raw = draft[c.name]
      if (raw === '' && c.defaultValue !== null) continue
      try {
        values[c.name] = coerceInput(classifyColumnType(c.dataType), raw)
      } catch (err) {
        setError(tr('grid.columnError', { name: c.name, message: errorText(err) }))
        return
      }
    }
    setBusy(true)
    setError(null)
    try {
      await unwrap(
        window.dbApi.insertRow({
          connectionId: selection.connectionId,
          database: selection.database,
          schema: selection.schema,
          table: selection.table,
          values
        })
      )
      setDraft(null)
      // The database fills in generated columns, so the new row has to come back
      // from the server. Refetch quietly and mark the row that was not there
      // before, which keeps the grid mounted and the user's place in it.
      const before = new Set((data?.rows ?? []).map((r) => rowKey(r, pks)))
      const result = await load({ quiet: true })
      const added = result?.rows.find((r) => !before.has(rowKey(r, pks)))
      if (added) markSaved(rowKey(added, pks))
    } catch (err) {
      setError(errorText(err))
    } finally {
      setBusy(false)
    }
  }

  function pkOf(row: Record<string, unknown>): Record<string, unknown> {
    const pk: Record<string, unknown> = {}
    for (const k of pks) pk[k] = row[k]
    return pk
  }

  async function deleteRows(rows: Record<string, unknown>[]): Promise<void> {
    if (rows.length === 0) return
    const label =
      rows.length === 1
        ? `PK ${JSON.stringify(pkOf(rows[0]))}`
        : tr('grid.selectedRows', { count: rows.length })
    const proceed = await confirmDestructive(tr('grid.deleteRowsConfirm', { label }), {
      title: tr('grid.deleteRowsTitle'),
      detail: tr('grid.deleteRowsDetail')
    })
    if (!proceed) return
    setBusy(true)
    setError(null)
    try {
      // One transaction for the whole selection: previously each row was a
      // separate call, so a failure in the middle deleted only part of them.
      await unwrap(
        window.dbApi.deleteRows(
          selection.connectionId,
          selection.database,
          selection.table,
          rows.map((row) => pkOf(row)),
          selection.schema
        )
      )
      setSelected(new Set())
      // Drop the rows locally instead of refetching the page: the remaining rows
      // stay exactly where they were and nothing flashes.
      const removed = new Set(rows.map((r) => rowKey(r, pks)))
      const remaining = (data?.rows ?? []).filter((r) => !removed.has(rowKey(r, pks)))
      const nextTotal = Math.max(0, (data?.total ?? 0) - rows.length)
      setData((prev) => (prev ? { ...prev, rows: remaining, total: nextTotal } : prev))
      const pageStart = page * pageSize
      if (remaining.length === 0 && nextTotal > 0) {
        // Nothing left on this page: step back, or ask the server for the page
        // that still has rows.
        if (page > 0) setPage((p) => Math.max(0, p - 1))
        else await load({ quiet: true })
      } else if (
        remaining.length < pageSize &&
        nextTotal > pageStart + remaining.length
      ) {
        // A short page would make the next page's offset skip the row that just
        // moved up, so pull one more row to keep the window contiguous.
        await load({ quiet: true })
      }
    } catch (err) {
      setError(errorText(err))
    } finally {
      setBusy(false)
    }
  }

  const selectedRows = (data?.rows ?? []).filter((r) => selected.has(rowKey(r, pks)))

  async function updateCell(
    rowIndex: number,
    column: string,
    value: unknown
  ): Promise<void> {
    if (!data) return
    const row = data.rows[rowIndex]
    setBusy(true)
    setError(null)
    try {
      await unwrap(
        window.dbApi.updateRow({
          connectionId: selection.connectionId,
          database: selection.database,
          schema: selection.schema,
          table: selection.table,
          primaryKeys: pkOf(row),
          changes: { [column]: value }
        })
      )
      patchRow(rowIndex, { [column]: value })
      markSaved(rowKey({ ...row, [column]: value }, pks))
      if (editNeedsRefetch(column)) await load({ quiet: true })
    } catch (err) {
      setError(errorText(err))
    } finally {
      setBusy(false)
    }
  }

  function copyCell(): void {
    if (!menu || !data) return
    const raw = data.rows[menu.rowIndex][menu.column]
    const column = columns.find((c) => c.name === menu.column)
    void window.dbApi.clipboardWrite(formatCellValue(raw, column?.dataType))
  }

  // Fills the cell with the database's own current time. The value is not sent
  // from here: the driver emits its now() expression, so a server in another
  // timezone writes its clock rather than the client's.
  async function setCellNow(rowIndex: number, column: string): Promise<void> {
    if (!data) return
    const info = columns.find((c) => c.name === column)
    const kind = classifyColumnType(info?.dataType ?? '')
    if (!isNowKind(kind)) return
    const row = data.rows[rowIndex]
    setBusy(true)
    setError(null)
    try {
      await unwrap(
        window.dbApi.updateRow({
          connectionId: selection.connectionId,
          database: selection.database,
          schema: selection.schema,
          table: selection.table,
          primaryKeys: pkOf(row),
          changes: {},
          nowColumns: [{ name: column, kind }]
        })
      )
      // The exact value comes from the server, so the row is reloaded instead of
      // guessed on the client.
      await load({ quiet: true })
    } catch (err) {
      setError(errorText(err))
    } finally {
      setBusy(false)
    }
  }

  async function pasteCell(): Promise<void> {
    if (!menu) return
    const res = await window.dbApi.clipboardRead()
    if (!res.ok) return
    const text = res.data ?? ''
    const column = columns.find((c) => c.name === menu.column)
    if (!column) return
    let value: unknown = text
    try {
      if (text !== '') value = coerceInput(classifyColumnType(column.dataType), text)
    } catch (err) {
      setError(tr('grid.columnError', { name: column.name, message: errorText(err) }))
      return
    }
    await updateCell(menu.rowIndex, menu.column, value)
  }

  function buildMenuItems(ctx: CellContext): MenuItem[] {
    if (!data) return []
    const column = columns.find((c) => c.name === ctx.column)
    const row = data.rows[ctx.rowIndex]
    const isNull = row[ctx.column] === null || row[ctx.column] === undefined
    const editable = canEdit && !busy
    const kind = classifyColumnType(column?.dataType ?? '')
    const nowable = isNowKind(kind)
    return [
      {
        label: tr('grid.editValue'),
        disabled: !editable,
        onSelect: () => {
          const raw = row[ctx.column]
          setEdit({
            rowIndex: ctx.rowIndex,
            column: ctx.column,
            value: editableCellValue(raw, column?.dataType)
          })
        }
      },
      {
        label: tr('grid.setNow'),
        disabled: !editable || !nowable,
        onSelect: () => void setCellNow(ctx.rowIndex, ctx.column)
      },
      {
        label: tr('grid.setNull'),
        disabled: !editable || isNull || !column?.nullable,
        onSelect: () => void updateCell(ctx.rowIndex, ctx.column, null)
      },
      {
        label: tr('grid.setEmpty'),
        disabled: !editable,
        onSelect: () => void updateCell(ctx.rowIndex, ctx.column, '')
      },
      {
        label: tr('grid.copyValue'),
        disabled: isNull,
        separatorBefore: true,
        onSelect: copyCell
      },
      {
        label: tr('grid.pasteCell'),
        disabled: !editable,
        onSelect: () => void pasteCell()
      },
      {
        label: tr('grid.copyRow'),
        separatorBefore: true,
        onSelect: () => {
          void window.dbApi.clipboardWrite(JSON.stringify(row, null, 2))
        }
      },
      {
        label: tr('grid.deleteRow'),
        danger: true,
        disabled: !editable,
        separatorBefore: true,
        onSelect: () => void deleteRows([row])
      }
    ]
  }

  return (
    <div className="grid-wrap">
      {menu && (
        <ContextMenu
          x={menu.x}
          y={menu.y}
          items={buildMenuItems(menu)}
          onClose={() => setMenu(null)}
        />
      )}
      <div className="grid-toolbar">
        <h2 className="grid-title">
          {selection.database}
          {selection.schema ? `.${selection.schema}` : ''}.{selection.table}
        </h2>
      </div>

      {/* Only once the page has loaded: `canEdit` is false while `data` is still
          null, so this used to flash a "no primary key" warning on every first
          open of a table that does have one, then take it away again. */}
      {data && !canEdit && (
        <p className="notice notice--info">{tr('grid.noPrimaryKeyNotice')}</p>
      )}

      {filtersOpen && (
        <div className="grid-filters">
          <span className="field__label">{tr('grid.combine')}</span>
          <select
            className="input grid-filters__logic"
            value={filterLogic}
            onChange={(e) => {
              setFilterLogic(e.target.value === 'or' ? 'or' : 'and')
              setPage(0)
            }}
            aria-label={tr('grid.combine')}
          >
            <option value="and">AND</option>
            <option value="or">OR</option>
          </select>
          <span className="settings__hint grid-filters__count">
            {activeFilters.length === 0
              ? tr('grid.noConditions')
              : tr('grid.filtersActive', { count: activeFilters.length })}
          </span>
          <button
            className="btn btn--tiny btn--ghost grid-filters__reset"
            onClick={() => {
              setAdvancedFilters([])
              setFilterLogic('and')
              setPage(0)
            }}
            disabled={advancedFilters.length === 0}
          >
            {tr('common.reset')}
          </button>
        </div>
      )}

      {filtersOpen && (
        <div className="grid-advfilters">
          {advancedFilters.map((filter, index) => (
            <div className="grid-advfilter" key={index}>
              <select
                className="input"
                value={filter.column}
                onChange={(e) => {
                  const next = [...advancedFilters]
                  next[index] = { ...next[index], column: e.target.value }
                  setAdvancedFilters(next)
                  setPage(0)
                }}
                aria-label={tr('grid.filterColumnLabel', { n: index + 1 })}
              >
                <option value="">{tr('qb.chooseColumn')}</option>
                {columns.map((c) => (
                  <option key={c.name} value={c.name}>
                    {c.name}
                  </option>
                ))}
              </select>
              <select
                className="input"
                value={filter.op}
                onChange={(e) => {
                  const next = [...advancedFilters]
                  next[index] = {
                    ...next[index],
                    op: e.target.value as FilterOperator
                  }
                  setAdvancedFilters(next)
                  setPage(0)
                }}
                aria-label={tr('grid.filterOperatorLabel', { n: index + 1 })}
              >
                {FILTER_OPERATORS.map((op) => (
                  <option key={op} value={op}>
                    {FILTER_OPERATOR_LABELS[op]}
                  </option>
                ))}
              </select>
              <input
                className="input"
                value={filter.value ?? ''}
                onChange={(e) => {
                  const next = [...advancedFilters]
                  next[index] = { ...next[index], value: e.target.value }
                  setAdvancedFilters(next)
                  setPage(0)
                }}
                disabled={!operatorNeedsValue(filter.op)}
                placeholder={
                  operatorNeedsValue(filter.op)
                    ? tr('grid.valuePlaceholder')
                    : tr('grid.valueNotNeeded')
                }
                aria-label={tr('grid.filterValueLabel', { n: index + 1 })}
              />
              <button
                className="icon-btn"
                onClick={() => {
                  setAdvancedFilters(advancedFilters.filter((_, i) => i !== index))
                  setPage(0)
                }}
                aria-label={tr('grid.removeFilterLabel', { n: index + 1 })}
                title={tr('grid.removeCondition')}
              >
                <IconRemove size={13} />
              </button>
            </div>
          ))}
          <button
            className="btn btn--tiny btn--ghost"
            onClick={() => {
              setAdvancedFilters([
                ...advancedFilters,
                { column: '', op: 'contains', value: '' }
              ])
            }}
            disabled={advancedFilters.length >= 20}
          >
            {tr('grid.addCondition')}
          </button>
        </div>
      )}

      {error && (
        <p className="notice notice--error" role="alert">
          {error}
        </p>
      )}

      <div className="grid-body" aria-busy={loading}>
        {/* The bordered shell is rendered before the rows arrive. It used to be
            replaced by a bare "Loading data..." line, so the first open of a
            table popped: text, then a full box with a pager at the bottom. A
            page or filter change had the same flash, because the previous rows
            were thrown away. Keeping the shell and dimming the old rows makes
            both transitions look like the same table filling in. */}
        {!data && !loading ? (
          <p className="muted">{tr('grid.columnsFailed')}</p>
        ) : (
          <div className={`table-scroll${loading && data ? ' is-loading' : ''}`}>
            {!data ? (
              <p className="muted grid-loading">{tr('grid.loadingData')}</p>
            ) : (
              <table className="data-table" style={{ width: totalWidth }}>
                <colgroup>
                  <col style={{ width: CHECKBOX_COL_WIDTH }} />
                  {columns.map((c) => (
                    <col key={c.name} style={{ width: widthOf(c.name) }} />
                  ))}
                  <col style={{ width: ACTIONS_COL_WIDTH }} />
                </colgroup>
                <thead>
                  <tr>
                    <th className="th-select">
                      <input
                        type="checkbox"
                        checked={allSelected}
                        onChange={toggleAll}
                        disabled={busy || !canEdit}
                        aria-label={tr('grid.selectAllRows')}
                      />
                    </th>
                    {columns.map((c) => (
                      <th
                        key={c.name}
                        className="th-col"
                        // Screen readers announce the sort state of the column
                        // instead of relying on the ▲/▼ glyph alone.
                        aria-sort={
                          orderBy === c.name
                            ? orderDir === 'asc'
                              ? 'ascending'
                              : 'descending'
                            : 'none'
                        }
                      >
                        <button className="th-btn" onClick={() => toggleSort(c.name)}>
                          <span className="th-name">{c.name}</span>
                          <span className="th-type">{c.dataType}</span>
                          {orderBy === c.name && (
                            <span className="th-sort" aria-hidden="true">
                              {orderDir === 'asc' ? '▲' : '▼'}
                            </span>
                          )}
                        </button>
                        <span
                          className="col-resizer"
                          onMouseDown={(e) => startResize(e, c.name)}
                          onKeyDown={(e) => resizeByKeyboard(e, c.name)}
                          tabIndex={0}
                          role="separator"
                          aria-orientation="vertical"
                          aria-label={tr('grid.resizeColumn', { name: c.name })}
                          title={tr('query.resizeHint')}
                        />
                      </th>
                    ))}
                    <th className="th-actions" />
                  </tr>
                </thead>
                <tbody>
                  {data.rows.length === 0 && !draft && (
                    <tr className="grid-empty">
                      <td className="cell grid-empty__cell" colSpan={columns.length + 2}>
                        {activeFilters.length > 0
                          ? tr('grid.rowsNoMatch')
                          : canEdit
                            ? tr('grid.emptyTable')
                            : tr('grid.emptyTableReadOnly')}
                      </td>
                    </tr>
                  )}
                  {data.rows.map((row, rowIndex) => {
                    const key = rowKey(row, pks) || String(rowIndex)
                    const isInspected =
                      inspectedRowKey !== null && inspectedRowKey === key
                    return (
                      <tr
                        key={key}
                        className={`${selected.has(key) ? 'is-selected' : ''}${
                          isInspected ? ' is-inspected' : ''
                        }${savedKey === key ? ' is-saved' : ''}`}
                        onClick={() => onInspectRow?.(row, key)}
                      >
                        <td className="cell cell--select">
                          <input
                            type="checkbox"
                            checked={selected.has(key)}
                            onChange={() => toggleRow(key)}
                            onClick={(e) => e.stopPropagation()}
                            disabled={busy || !canEdit}
                            aria-label={tr('grid.selectRow')}
                          />
                        </td>
                        {columns.map((c) => {
                          const isEditing =
                            edit?.rowIndex === rowIndex && edit.column === c.name
                          const raw = row[c.name]
                          const kind = classifyColumnType(c.dataType)
                          const text = editableCellValue(raw, c.dataType)
                          return (
                            <td
                              key={c.name}
                              className={c.isPrimaryKey ? 'cell cell--pk' : 'cell'}
                              onDoubleClick={() => {
                                if (!canEdit || busy || isBinaryCell(raw)) return
                                setEdit({ rowIndex, column: c.name, value: text })
                              }}
                              onContextMenu={(e) => {
                                e.preventDefault()
                                setMenu({
                                  x: e.clientX,
                                  y: e.clientY,
                                  rowIndex,
                                  column: c.name
                                })
                              }}
                            >
                              {isEditing ? (
                                kind === 'boolean' ? (
                                  <select
                                    className="cell-input"
                                    autoFocus
                                    value={edit.value}
                                    onChange={(e) =>
                                      setEdit({ ...edit, value: e.target.value })
                                    }
                                    onBlur={() => void commitEdit()}
                                    onKeyDown={(e) => {
                                      if (e.key === 'Escape') setEdit(null)
                                    }}
                                  >
                                    <option value="true">true</option>
                                    <option value="false">false</option>
                                  </select>
                                ) : (
                                  <input
                                    className="cell-input"
                                    type={inputElementType(kind)}
                                    autoFocus
                                    value={edit.value}
                                    onChange={(e) =>
                                      setEdit({ ...edit, value: e.target.value })
                                    }
                                    onBlur={() => void commitEdit()}
                                    onKeyDown={(e) => {
                                      if (e.key === 'Enter') void commitEdit()
                                      if (e.key === 'Escape') setEdit(null)
                                    }}
                                  />
                                )
                              ) : raw === null ? (
                                <span className="cell-null">NULL</span>
                              ) : isBinaryCell(raw) ? (
                                <button
                                  className="blob-badge"
                                  onClick={(e) => {
                                    e.stopPropagation()
                                    setPreview(raw)
                                  }}
                                  title={tr('grid.viewBinary')}
                                >
                                  {raw.kind === 'image' && raw.dataUrl ? (
                                    <img
                                      className="blob-badge__thumb"
                                      src={raw.dataUrl}
                                      alt=""
                                    />
                                  ) : (
                                    <span className="blob-badge__icon" aria-hidden="true">
                                      BLOB
                                    </span>
                                  )}
                                  <span className="blob-badge__size">
                                    {formatBytes(raw.size)}
                                  </span>
                                </button>
                              ) : (
                                formatCellValue(raw, c.dataType)
                              )}
                            </td>
                          )
                        })}
                        <td className="cell cell--actions">
                          <button
                            className="icon-btn icon-btn--danger"
                            onClick={(e) => {
                              e.stopPropagation()
                              void deleteRows([row])
                            }}
                            disabled={busy || !canEdit}
                            title={tr('grid.deleteRowTitle')}
                            aria-label={tr('grid.deleteRowTitle')}
                          >
                            <IconTrash />
                          </button>
                        </td>
                      </tr>
                    )
                  })}
                  {draft && (
                    <tr className="draft-row">
                      <td className="cell cell--select" />
                      {columns.map((c) => {
                        if (!(c.name in draft)) {
                          return (
                            <td key={c.name} className="cell cell--pk">
                              <span className="cell-null">{tr('grid.autoValue')}</span>
                            </td>
                          )
                        }
                        const kind = classifyColumnType(c.dataType)
                        const type = inputElementType(kind)
                        const isFirst = Object.keys(draft)[0] === c.name
                        return (
                          <td key={c.name} className="cell cell--edit">
                            {kind === 'boolean' ? (
                              <select
                                className="cell-input"
                                value={draft[c.name]}
                                autoFocus={isFirst}
                                onChange={(e) =>
                                  setDraft({ ...draft, [c.name]: e.target.value })
                                }
                              >
                                <option value="true">true</option>
                                <option value="false">false</option>
                              </select>
                            ) : (
                              <input
                                className="cell-input"
                                type={type}
                                value={draft[c.name]}
                                autoFocus={isFirst}
                                placeholder={c.defaultValue !== null ? 'default' : ''}
                                onChange={(e) =>
                                  setDraft({ ...draft, [c.name]: e.target.value })
                                }
                              />
                            )}
                          </td>
                        )
                      })}
                      <td className="cell cell--actions">
                        <button
                          className="icon-btn icon-btn--ok"
                          onClick={() => void commitDraft()}
                          disabled={busy}
                          title={tr('grid.saveRow')}
                          aria-label={tr('grid.saveRow')}
                        >
                          <IconCheck />
                        </button>
                        <button
                          className="icon-btn"
                          onClick={() => setDraft(null)}
                          disabled={busy}
                          title={tr('grid.cancel')}
                          aria-label={tr('grid.cancel')}
                        >
                          <IconClose />
                        </button>
                      </td>
                    </tr>
                  )}
                </tbody>
              </table>
            )}
          </div>
        )}
      </div>

      {/* The pager keeps its height while the first page loads, so the table
          does not grow by 35px the moment the rows arrive. */}
      {!data && loading && (
        <div className="pager pager--placeholder" aria-hidden="true" />
      )}
      {data && (
        <div className="pager">
          <div className="pager__nav">
            <button
              className="pager__btn"
              onClick={() => setPage(0)}
              disabled={page === 0 || busy}
              title={tr('grid.firstPage')}
              aria-label={tr('grid.firstPage')}
            >
              <IconChevron direction="left" double />
            </button>
            <button
              className="pager__btn"
              onClick={() => setPage((p) => Math.max(0, p - 1))}
              disabled={page === 0 || busy}
              title={tr('grid.prevPage')}
              aria-label={tr('grid.prevPage')}
            >
              <IconChevron direction="left" />
            </button>
            <span className="pager__jump">
              <input
                className="input pager__jump-input"
                type="number"
                min={1}
                max={totalPages}
                value={pageDraft === '' ? page + 1 : pageDraft}
                onChange={(e) => setPageDraft(e.target.value)}
                onFocus={(e) => e.target.select()}
                onBlur={() => setPageDraft('')}
                onKeyDown={(e) => {
                  if (e.key === 'Escape') {
                    setPageDraft('')
                    e.currentTarget.blur()
                    return
                  }
                  if (e.key !== 'Enter') return
                  // Enter commits the typed page. Out-of-range values clamp
                  // instead of erroring, because a typo should not cost a load.
                  const next = Number(e.currentTarget.value)
                  if (!Number.isFinite(next) || next < 1) {
                    setPageDraft('')
                    return
                  }
                  const target = Math.min(totalPages, Math.max(1, Math.round(next))) - 1
                  setPage(target)
                  setPageDraft('')
                  e.currentTarget.blur()
                }}
                disabled={busy || totalPages <= 1}
                aria-label={tr('grid.pageRange', { total: totalPages })}
                title={tr('grid.pageJump')}
              />
              <span className="pager__jump-total">/ {totalPages}</span>
            </span>
            <button
              className="pager__btn"
              onClick={() => setPage((p) => Math.min(totalPages - 1, p + 1))}
              disabled={page >= totalPages - 1 || busy}
              title={tr('grid.nextPage')}
              aria-label={tr('grid.nextPage')}
            >
              <IconChevron direction="right" />
            </button>
            <button
              className="pager__btn"
              onClick={() => setPage(totalPages - 1)}
              disabled={page >= totalPages - 1 || busy}
              title={tr('grid.lastPage')}
              aria-label={tr('grid.lastPage')}
            >
              <IconChevron direction="right" double />
            </button>
          </div>
          <span className="pager__info">
            {data.total === 0
              ? tr('grid.rowsEmpty')
              : tr('grid.rowsRange', {
                  from: data.rows.length === 0 ? 0 : page * pageSize + 1,
                  to: page * pageSize + data.rows.length,
                  total: data.total,
                  count: data.total
                })}
          </span>

          <label className="field field--inline pager__size">
            <span className="field__label">{tr('grid.perPage')}</span>
            <select
              className="input"
              value={pageSize}
              onChange={(e) => {
                setPageSize(Number(e.target.value))
                setPage(0)
              }}
              disabled={busy}
            >
              {PAGE_SIZE_OPTIONS.map((size) => (
                <option key={size} value={size}>
                  {size}
                </option>
              ))}
            </select>
          </label>

          <div className="pager__actions">
            {selected.size > 0 && (
              <button
                className="icon-btn icon-btn--danger"
                onClick={() => void deleteRows(selectedRows)}
                disabled={busy || !canEdit}
                title={tr('grid.deleteSelected', { count: selected.size })}
                aria-label={tr('grid.deleteSelected', { count: selected.size })}
              >
                <IconTrash />
                <span className="icon-btn__badge">{selected.size}</span>
              </button>
            )}
            <button
              className="icon-btn"
              onClick={startDraft}
              disabled={busy || !canInsert || draft !== null}
              title={canInsert ? tr('grid.addRow') : tr('grid.noColumnsYet')}
              aria-label={tr('grid.addRow')}
            >
              <IconPlus />
            </button>
            <button
              className="icon-btn"
              onClick={() => void load()}
              disabled={busy}
              title={tr('menu.reload')}
              aria-label={tr('menu.reload')}
            >
              <IconReload />
            </button>
          </div>
        </div>
      )}

      {preview && (
        <div
          className="modal-backdrop"
          role="dialog"
          aria-modal="true"
          aria-label={tr('grid.previewBinary')}
          onClick={() => setPreview(null)}
        >
          <div className="modal modal--preview" onClick={(e) => e.stopPropagation()}>
            <div className="modal__head">
              <h2>{tr('grid.previewBinary')}</h2>
              <button
                className="btn btn--ghost btn--small"
                onClick={() => setPreview(null)}
              >
                {tr('common.close')}
              </button>
            </div>
            <p className="muted preview__meta">
              {preview.mime} · {formatBytes(preview.size)}
            </p>
            {preview.kind === 'image' && preview.dataUrl ? (
              <div className="preview__image">
                <img src={preview.dataUrl} alt={tr('grid.previewImage')} />
              </div>
            ) : preview.kind === 'text' && preview.text !== undefined ? (
              <pre className="sql-preview preview__text">{preview.text}</pre>
            ) : (
              <>
                {preview.size > 512 * 1024 && (
                  <p className="notice notice--info">
                    Biner besar ({formatBytes(preview.size)}); hanya sebagian ditampilkan.
                  </p>
                )}
                <pre className="sql-preview preview__hex">{preview.hex}</pre>
              </>
            )}
          </div>
        </div>
      )}
    </div>
  )
}
