import { describe, expect, it } from 'vitest'
import { isAutoGeneratedColumn } from '@shared/columnType'

// A generated key must never be sent on insert. When the insert form sent an
// explicit 0 for SQLite's rowid alias, every new row landed on id 0 and the
// "auto" column silently stopped being auto.
describe('isAutoGeneratedColumn', () => {
  it('trusts the driver flag', () => {
    expect(isAutoGeneratedColumn('INTEGER', null, true)).toBe(true)
    expect(isAutoGeneratedColumn('number', null, true)).toBe(true)
  })

  it('recognises serial types and nextval defaults', () => {
    expect(isAutoGeneratedColumn('serial', null, false)).toBe(true)
    expect(isAutoGeneratedColumn('bigserial', null, false)).toBe(true)
    expect(
      isAutoGeneratedColumn('integer', "nextval('orders_id_seq'::regclass)", false)
    ).toBe(true)
    expect(isAutoGeneratedColumn('INTEGER', null, false)).toBe(false)
  })

  it('does not treat a plain column as generated', () => {
    expect(isAutoGeneratedColumn('TEXT', null, false)).toBe(false)
    expect(isAutoGeneratedColumn('INTEGER', '0', false)).toBe(false)
    expect(isAutoGeneratedColumn('integer', 'CURRENT_TIMESTAMP', false)).toBe(false)
  })
})
