)
SELECT format('TRX-%s', lpad((100 + n)::text, 6, '0')),
       timestamptz '2026-06-10 08:00:00+07' + n * interval '13 minutes',
       format('K%s', lpad((((n * 7 - 1) % 50) + 1)::text, 2, '0')),
       format('P%s', lpad((((n * 11 - 1) % 50) + 1)::text, 2, '0')),
       format('C%s %s', lpad((((n * 3 - 1) % 50) + 1)::text, 2, '0'),
         (ARRAY['Jakarta','Bandung','Surabaya','Yogyakarta','Semarang'])[((n * 3 - 1) % 5) + 1]),
       CASE WHEN n % 17 = 0 THEN 'dibatalkan' WHEN n % 9 = 0 THEN 'menunggu' ELSE 'selesai' END,
       calc.subtotal,
       calc.diskon,
       calc.subtotal - calc.diskon,
       (ARRAY['tunai','kartu','QRIS','transfer'])[((n - 1) % 4) + 1]
FROM generate_series(1, 100) AS n
CROSS JOIN LATERAL (
  SELECT (78000 + (n * 13871 % 925000))::numeric(14,2) AS subtotal,
         CASE WHEN n % 4 = 0 THEN round((78000 + (n * 13871 % 925000))::numeric * 0.1, 2) ELSE 0::numeric END AS diskon
) calc
WHERE NOT EXISTS (
  SELECT 1 FROM public.transaksi_kasir t
  WHERE t.nomor_struk = format('TRX-%s', lpad((100 + n)::text, 6, '0'))
);

