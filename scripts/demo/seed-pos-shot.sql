FROM generate_series(1, 50) AS n
JOIN public.purchase_orders po ON po.po_number = format('PB-2026-%s', lpad(n::text, 4, '0'))
CROSS JOIN (VALUES (1), (2), (3)) AS line(line_no)
JOIN LATERAL (
  SELECT p0.id, p0.price FROM public.products p0
  WHERE p0.name LIKE 'Kopi Arabika %' OR p0.name LIKE 'Teh Melati %' OR p0.name LIKE 'Roti Gandum %'
  ORDER BY p0.name OFFSET ((n + line.line_no - 2) % 15) LIMIT 1
) p ON true
WHERE NOT EXISTS (SELECT 1 FROM public.purchase_order_items poi WHERE poi.purchase_order_id = po.id AND poi.line_no = line.line_no);

