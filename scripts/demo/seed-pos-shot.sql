WITH pool AS (
  SELECT array_agg(id ORDER BY name) AS product_ids FROM public.products
  WHERE name LIKE 'Kopi Arabika %' OR name LIKE 'Teh Melati %' OR name LIKE 'Roti Gandum %'
)
INSERT INTO public.order_items (order_id, product_id, qty, unit_price)
SELECT o.id, pool.product_ids[((n - 1) % cardinality(pool.product_ids)) + 1],
       1 + n % 4, p.price
FROM generate_series(1, 50) AS n
JOIN public.orders o ON o.created_at = timestamp '2026-06-10 08:00:00' + n * interval '19 minutes'
JOIN public.users u ON u.id = o.user_id AND u.email LIKE 'screenshot.kasir.%@tupai.local'
CROSS JOIN pool
JOIN public.products p ON p.id = pool.product_ids[((n - 1) % cardinality(pool.product_ids)) + 1]
WHERE NOT EXISTS (SELECT 1 FROM public.order_items oi WHERE oi.order_id = o.id);

INSERT INTO public.payments (order_id, method, amount, paid_at)
SELECT o.id, (ARRAY['cash','card','qris'])[((row_number() OVER (ORDER BY o.created_at) - 1) % 3) + 1],
       o.total, o.created_at + interval '3 minutes'
FROM public.orders o
JOIN public.users u ON u.id = o.user_id AND u.email LIKE 'screenshot.kasir.%@tupai.local'
WHERE o.created_at >= timestamp '2026-06-10 08:19:00'
  AND o.created_at <= timestamp '2026-06-10 08:00:00' + 50 * interval '19 minutes'
  AND o.status = 'paid'
  AND NOT EXISTS (SELECT 1 FROM public.payments p WHERE p.order_id = o.id);

