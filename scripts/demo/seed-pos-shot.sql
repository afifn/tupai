CREATE TABLE IF NOT EXISTS public.transaksi_kasir (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nomor_struk varchar(28) NOT NULL UNIQUE,
  waktu timestamptz NOT NULL,
  kasir varchar(48) NOT NULL,
  pelanggan varchar(48) NOT NULL,
  cabang varchar(48) NOT NULL,
  status varchar(16) NOT NULL CHECK (status IN ('selesai','menunggu','dibatalkan')),
  subtotal numeric(14,2) NOT NULL CHECK (subtotal >= 0),
  diskon numeric(12,2) NOT NULL CHECK (diskon >= 0),
  total numeric(14,2) NOT NULL CHECK (total >= 0),
  metode_bayar varchar(20) NOT NULL CHECK (metode_bayar IN ('tunai','kartu','QRIS','transfer'))
);

CREATE TABLE IF NOT EXISTS public.pesanan_demo (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pelanggan_id integer NOT NULL,
  status varchar(16) NOT NULL CHECK (status IN ('baru','diproses','dikirim','selesai','dibatalkan')),
  total numeric(12,2) NOT NULL CHECK (total >= 0),
  metode varchar(20) NOT NULL CHECK (metode IN ('transfer','kartu kredit','e-wallet','cod')),
  tanggal date NOT NULL,
  cabang varchar(48) NOT NULL
);

