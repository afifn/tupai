WITH pools AS (
  SELECT array_agg(id ORDER BY name) AS product_ids
  FROM public.products WHERE name LIKE 'Demo Produk %'
), user_pool AS (
  SELECT array_agg(id ORDER BY email) AS ids FROM public.users WHERE email LIKE 'demo.kasir.%@tupai.local'
), order_input AS (
  SELECT n,
    up.ids[((n * 7 - 1) % cardinality(up.ids)) + 1] AS user_id,
    timestamp '2026-06-10 08:00:00' + n * interval '19 minutes' AS created_at,
    (pp.product_ids[((n - 1) % cardinality(pp.product_ids)) + 1]) AS p1,
    (pp.product_ids[((n * 3 - 1) % cardinality(pp.product_ids)) + 1]) AS p2,
    (1 + n % 4) AS q1,
    (1 + (n * 3) % 3) AS q2
  FROM generate_series(1, 60) AS n
  CROSS JOIN pools pp
  CROSS JOIN user_pool up
), order_totals AS (
  SELECT oi.*, pr1.price * oi.q1 + pr2.price * oi.q2 AS total
  FROM order_input oi
  JOIN public.products pr1 ON pr1.id = oi.p1
  JOIN public.products pr2 ON pr2.id = oi.p2
)
