CREATE TABLE IF NOT EXISTS public.suppliers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(120) NOT NULL UNIQUE,
  contact_name varchar(100) NOT NULL,
  email varchar(160) NOT NULL UNIQUE,
  city varchar(80) NOT NULL,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.customers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(120) NOT NULL,
  email varchar(160) NOT NULL UNIQUE,
  phone varchar(24) NOT NULL,
  loyalty_points integer NOT NULL DEFAULT 0 CHECK (loyalty_points >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.branches (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL UNIQUE,
  city varchar(80) NOT NULL,
  address varchar(180) NOT NULL,
  opened_at date NOT NULL,
  active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public.register_shifts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_code varchar(40) NOT NULL UNIQUE,
  branch_id integer NOT NULL REFERENCES public.branches(id),
  cashier_id integer NOT NULL REFERENCES public.users(id),
  opened_at timestamptz NOT NULL,
  closed_at timestamptz,
  opening_cash numeric(12,2) NOT NULL CHECK (opening_cash >= 0),
  closing_cash numeric(12,2) CHECK (closing_cash >= 0),
  status varchar(16) NOT NULL CHECK (status IN ('open','closed','review'))
);

CREATE TABLE IF NOT EXISTS public.stock_movements (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movement_ref varchar(48) NOT NULL UNIQUE,
  product_id integer NOT NULL REFERENCES public.products(id),
  branch_id integer NOT NULL REFERENCES public.branches(id),
  movement_type varchar(20) NOT NULL CHECK (movement_type IN ('receive','sale','adjustment','return')),
  quantity integer NOT NULL CHECK (quantity <> 0),
  note varchar(180) NOT NULL,
  created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS public.discounts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(32) NOT NULL UNIQUE,
  description varchar(140) NOT NULL,
  discount_type varchar(12) NOT NULL CHECK (discount_type IN ('percent','amount')),
  discount_value numeric(10,2) NOT NULL CHECK (discount_value > 0),
  active boolean NOT NULL DEFAULT true,
  starts_at date NOT NULL,
  ends_at date NOT NULL CHECK (ends_at >= starts_at)
);

CREATE TABLE IF NOT EXISTS public.purchase_orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  po_number varchar(40) NOT NULL UNIQUE,
  supplier_id integer NOT NULL REFERENCES public.suppliers(id),
  branch_id integer NOT NULL REFERENCES public.branches(id),
  status varchar(16) NOT NULL CHECK (status IN ('draft','sent','received','partial')),
  total numeric(14,2) NOT NULL CHECK (total >= 0),
  ordered_at date NOT NULL,
  received_at date
);

CREATE TABLE IF NOT EXISTS public.purchase_order_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_order_id integer NOT NULL REFERENCES public.purchase_orders(id),
  line_no integer NOT NULL,
  product_id integer NOT NULL REFERENCES public.products(id),
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_cost numeric(12,2) NOT NULL CHECK (unit_cost >= 0),
  UNIQUE (purchase_order_id, line_no)
);

CREATE TABLE IF NOT EXISTS public.expenses (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expense_ref varchar(48) NOT NULL UNIQUE,
  branch_id integer NOT NULL REFERENCES public.branches(id),
  category varchar(48) NOT NULL,
  description varchar(160) NOT NULL,
  amount numeric(12,2) NOT NULL CHECK (amount > 0),
  payment_method varchar(16) NOT NULL CHECK (payment_method IN ('cash','transfer','card')),
  paid_at timestamptz NOT NULL
);

